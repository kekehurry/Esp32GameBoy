    def display_info(self):
        self.display.fill(0)
        text = self.menu_list[self.cursor]
        self.display.text(text,self.display.width//2-len(text)*4,self.display.height-8,1)
        buffer = bytearray(self.icon_list[text])
        fb = framebuf.FrameBuffer(buffer, 40, 40, framebuf.MONO_HLSB)
        self.display.blit(fb,self.display.width//2-20,8)
        left = bytearray(self.icon_list["left"])
        left_fb = framebuf.FrameBuffer(left, 16, 16, framebuf.MONO_HLSB)
        self.display.blit(left_fb ,0,self.display.height//2-4)
        right = bytearray(self.icon_list["right"])
        right_fb = framebuf.FrameBuffer(right, 16, 16, framebuf.MONO_HLSB)
        self.display.blit(right_fb,self.display.width-16,self.display.height//2-4)
        self.display.show()
        
    def update(self,button):
        if button == 4:
            self.cursor -=1
        if button == 6:
            self.cursor +=1
        if self.cursor<0:
            self.cursor = len(self.menu_list)-1
        if self.cursor>len(self.menu_list)-1:
            self.cursor = 0
        if button == 1:
            self.mode = self.menu_list[self.cursor]
        if button == 2:
            self.mode = "wifi"
        self.display_info()
        sleep_ms(100)
        return self.mode
        
        